interface I18nContextType {
  locale: SupportedLocale;
  setLocale: (loc: SupportedLocale) => void;
  t: (key: string, fallback?: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  locale: 'en',
  setLocale: () => {},
  t: (key: string, fallback?: string) => fallback || key,
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [locale, setLocaleState] = useState<SupportedLocale>('en');

  useEffect(() => {
    try {
      const saved = localStorage.getItem('nyaya_locale') as SupportedLocale;
      if (saved && TRANSLATIONS[saved]) {
        setLocaleState(saved);
      }
    } catch {
      // Keep the default locale when browser storage is unavailable.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = (newLocale: SupportedLocale) => {
    setLocaleState(newLocale);
    try {
      localStorage.setItem('nyaya_locale', newLocale);
    } catch {
      // The selection still applies for the current page when storage is unavailable.
    }
  };

  const t = (key: string, fallback?: string): string => {
    return (
      UI_TRANSLATIONS[locale]?.[key] ||
      TRANSLATIONS[locale]?.[key] ||
      UI_TRANSLATIONS.en[key] ||
      TRANSLATIONS.en[key] ||
      fallback ||
      key
    );
  };

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => useContext(I18nContext);
